"""
kine2go.py - Slide 4 demo: a peek inside the Kine2Go motion library.

Two data paths:
  1. REAL:      list the files in the Hugging Face repo, find ONE motion.npy
                and download just that file (never the ~31 GB dataset).
  2. SYNTHETIC: if there is no internet, the download fails, or the file does
                not have the expected (T, 61) shape, load the bundled sample in
                data/kine2go_synthetic_sample/. That sample was generated by
                make_synthetic_sample() below and is CLEARLY labelled synthetic
                everywhere it is shown. It is a hand-made trot, NOT Kine2Go data.

Facts used from the notes: 60 Hz, motion.npy shape (T, 61), foot positions in
columns 36:48. The meaning of the other columns is the app's ASSUMED layout in
config.KINE2GO_ASSUMED_LAYOUT.
"""
import io
import time
from concurrent.futures import ThreadPoolExecutor, TimeoutError as FutTimeout

import numpy as np
from PIL import Image

import config
from demos.style import plt, toy_label

L = config.KINE2GO_ASSUMED_LAYOUT

# Toy leg geometry used ONLY to build the synthetic sample (not Go2 specs)
_HIP_X, _HIP_Y = 0.19, 0.13     # hip offsets from body centre (m)
_L1, _L2 = 0.21, 0.21           # thigh and calf lengths (m)
_BODY_H = 0.30                  # body height (m)


# ----------------------------------------------------------------------------
# Synthetic sample
# ----------------------------------------------------------------------------
def make_synthetic_sample(seconds=10.0, vx=0.25, period=0.6, duty=0.6, seed=config.RANDOM_SEED):
    """Build a slow, careful synthetic trot as a (T, 61) array in the app's
    assumed column layout. The feet are planned in the world frame (planted
    during stance, arcs during swing) and joint angles come from 2-link IK."""
    rng = np.random.default_rng(seed)
    fps = config.KINE2GO_FPS
    t = np.arange(0, seconds, 1.0 / fps)
    T = len(t)
    data = np.zeros((T, config.KINE2GO_N_COLS), dtype=np.float32)

    # Base motion: steady forward walk with a little sway and bob
    base = np.stack([vx * t, 0.01 * np.sin(2 * np.pi * t / period),
                     _BODY_H + 0.005 * np.cos(4 * np.pi * t / period)], axis=1)
    hips = [(+_HIP_X, -_HIP_Y), (+_HIP_X, +_HIP_Y), (-_HIP_X, -_HIP_Y), (-_HIP_X, +_HIP_Y)]
    phase_offset = [0.0, 0.5, 0.5, 0.0]          # trot: diagonal legs together
    step = vx * period                             # distance covered per cycle
    joints = np.zeros((T, 12))
    feet = np.zeros((T, 12))
    for leg, ((hx, hy), off) in enumerate(zip(hips, phase_offset)):
        ph = ((t / period) + off) % 1.0
        cycle = np.floor((t / period) + off)
        hip_x = base[:, 0] + hx
        # stance foot sits where it touched down; swing foot arcs forward
        touchdown_x = (cycle - off) * period * vx + hx + duty * step / 2
        in_stance = ph < duty
        s = np.clip((ph - duty) / (1 - duty), 0, 1)                # swing progress
        fx = np.where(in_stance, touchdown_x, touchdown_x + step * (0.5 - 0.5 * np.cos(np.pi * s)))
        fz = np.where(in_stance, 0.0, 0.06 * np.sin(np.pi * s))
        fy = np.full(T, hy * 1.05)
        feet[:, 3 * leg:3 * leg + 3] = np.stack([fx, fy, fz], axis=1)
        # 2-link IK in the sagittal plane (hip -> foot)
        dx, dz = fx - hip_x, fz - base[:, 2]
        D = np.clip((dx ** 2 + dz ** 2 - _L1 ** 2 - _L2 ** 2) / (2 * _L1 * _L2), -1, 1)
        calf = -np.arccos(D)
        thigh = np.arctan2(-dx, -dz) - np.arctan2(_L2 * np.sin(calf), _L1 + _L2 * np.cos(calf))
        abd = 0.03 * np.sin(2 * np.pi * t / period + np.pi * off)
        joints[:, 3 * leg:3 * leg + 3] = np.stack([abd, thigh, calf], axis=1)

    jv = np.gradient(joints, 1.0 / fps, axis=0)
    roll = 0.02 * np.sin(2 * np.pi * t / period)
    pitch = 0.015 * np.sin(4 * np.pi * t / period)
    quat = np.stack([np.cos(roll / 2) * np.cos(pitch / 2), np.sin(roll / 2) * np.cos(pitch / 2),
                     np.cos(roll / 2) * np.sin(pitch / 2), -np.sin(roll / 2) * np.sin(pitch / 2)], axis=1)
    data[:, L["joint_pos"]] = joints
    data[:, L["joint_vel"]] = jv
    data[:, L["actions"]] = joints + rng.normal(0, 0.01, joints.shape)
    data[:, L["foot_pos"]] = feet
    data[:, L["base_pos"]] = base
    data[:, L["base_quat"]] = quat
    data[:, L["base_lin_vel"]] = np.gradient(base, 1.0 / fps, axis=0)
    data[:, L["base_ang_vel"]] = np.stack([np.gradient(roll, 1 / fps), np.gradient(pitch, 1 / fps),
                                           np.zeros(T)], axis=1)
    return data


def ensure_synthetic_sample():
    """Create the bundled synthetic file if it is missing."""
    path = config.KINE2GO_SYNTHETIC_PATH
    if not path.exists():
        path.parent.mkdir(parents=True, exist_ok=True)
        np.save(path, make_synthetic_sample())
    return path


# ----------------------------------------------------------------------------
# Real download (optional)
# ----------------------------------------------------------------------------
def _find_and_download():
    """List the repo files, pick the first motion.npy and download only it."""
    from huggingface_hub import HfApi, hf_hub_download

    files = HfApi().list_repo_files(config.KINE2GO_REPO_ID, repo_type=config.KINE2GO_REPO_TYPE)
    matches = sorted(f for f in files if f.split("/")[-1] == config.KINE2GO_TARGET_NAME)
    if not matches:
        raise FileNotFoundError(f"no file named {config.KINE2GO_TARGET_NAME} in the repo listing "
                                f"({len(files)} files listed)")
    repo_path = matches[0]
    local = hf_hub_download(config.KINE2GO_REPO_ID, repo_path, repo_type=config.KINE2GO_REPO_TYPE,
                            local_dir=str(config.KINE2GO_CACHE_DIR))
    return local, repo_path, len(matches)


def try_download(timeout=config.KINE2GO_TIMEOUT_S):
    """Try to download one real motion.npy. Never raises; returns
    (local_path or None, message)."""
    pool = ThreadPoolExecutor(max_workers=1)
    future = pool.submit(_find_and_download)
    try:
        local, repo_path, n = future.result(timeout=timeout)
        return local, f"Downloaded `{repo_path}` (1 of {n} motion.npy files in the repo)."
    except FutTimeout:
        return None, f"Download timed out after {timeout} s."
    except Exception as exc:  # no internet, proxy, repo layout changed, ...
        return None, f"Download failed: {type(exc).__name__}: {str(exc)[:200]}"
    finally:
        pool.shutdown(wait=False, cancel_futures=True)


def _cached_real_file():
    hits = sorted(config.KINE2GO_CACHE_DIR.rglob(config.KINE2GO_TARGET_NAME)) \
        if config.KINE2GO_CACHE_DIR.exists() else []
    return hits[0] if hits else None


def load_motion(download=False):
    """Return dict(data, synthetic, message, path). Falls back to the
    synthetic sample automatically."""
    msg = ""
    path = _cached_real_file()
    if path is None and download:
        path, msg = try_download()
    elif path is not None:
        msg = f"Using previously downloaded file `{path.name}` from the local cache."
    if path is not None:
        try:
            arr = np.load(path, allow_pickle=False)
            if arr.ndim == 2 and arr.shape[1] == config.KINE2GO_N_COLS:
                return {"data": arr.astype(np.float64), "synthetic": False, "message": msg,
                        "path": str(path)}
            msg = f"Downloaded file has shape {arr.shape}, expected (T, 61)."
        except Exception as exc:
            msg = f"Could not read the downloaded file: {exc}"
    synth = ensure_synthetic_sample()
    if not msg:
        msg = "Download not attempted."
    return {"data": np.load(synth).astype(np.float64), "synthetic": True,
            "message": msg + " Using the bundled SYNTHETIC sample instead.", "path": str(synth)}


# ----------------------------------------------------------------------------
# Figures
# ----------------------------------------------------------------------------
def _tag(synthetic):
    return "SYNTHETIC SAMPLE - not Kine2Go data" if synthetic else "Real Kine2Go file"


def joint_figure(data, synthetic, seconds=4.0):
    fps = config.KINE2GO_FPS
    n = min(len(data), int(seconds * fps))
    t = np.arange(n) / fps
    fig, ax = plt.subplots(figsize=(7.2, 4.0))
    cols = [config.NAVY, config.ACCENT, config.ACCENT_2]
    for j in range(3):
        ax.plot(t, data[:n, j], lw=2.4, color=cols[j],
                label=f"col {j}: {config.KINE2GO_JOINT_NAMES[j]} (assumed)")
    ax.set_xlabel("time (s) at 60 Hz")
    ax.set_ylabel("joint angle (rad)")
    ax.set_title("Joint angles of one leg (columns 0-2)")
    ax.legend(loc="center right", fontsize=9.5)
    if synthetic:
        toy_label(ax, _tag(True))
    return fig


def foot_figure(data, synthetic, seconds=4.0):
    fps = config.KINE2GO_FPS
    n = min(len(data), int(seconds * fps))
    feet = data[:n, config.KINE2GO_FOOT_COLS].reshape(n, 4, 3)
    fig, ax = plt.subplots(figsize=(7.2, 4.0))
    cols = [config.NAVY, config.ACCENT, config.ACCENT_2, "#8E6CEF"]
    for f in range(4):
        ax.plot(feet[:, f, 0], feet[:, f, 2] + 0.0 * f, lw=2.2, color=cols[f],
                label=config.KINE2GO_FOOT_NAMES[f])
    ax.set_xlabel("foot x (m)")
    ax.set_ylabel("foot z (m)")
    ax.set_title("Foot trajectories, side view (columns 36:48)")
    ax.legend(loc="upper left", ncol=4, fontsize=9.5)
    zmin, zmax = feet[:, :, 2].min(), feet[:, :, 2].max()
    ax.set_ylim(zmin - 0.02, zmax + 0.05 + 0.25 * (zmax - zmin))
    if synthetic:
        toy_label(ax, _tag(True), loc="lower right")
    return fig


def footfall_figure(data, synthetic):
    """Static top-down footfall plot (also used in the PPTX)."""
    feet = data[:, config.KINE2GO_FOOT_COLS].reshape(len(data), 4, 3)
    base = data[:, L["base_pos"]]
    fig, ax = plt.subplots(figsize=(7.2, 4.0))
    cols = [config.NAVY, config.ACCENT, config.ACCENT_2, "#8E6CEF"]
    ax.plot(base[:, 0], base[:, 1], color=config.GREY, lw=2, ls="--", label="base path (assumed cols 48:50)")
    for f in range(4):
        z = feet[:, f, 2]
        contact = z < z.min() + 0.01
        ax.scatter(feet[contact, f, 0], feet[contact, f, 1], s=26, color=cols[f],
                   label=f"{config.KINE2GO_FOOT_NAMES[f]} contact")
    ax.set_xlabel("x (m)")
    ax.set_ylabel("y (m)")
    ax.set_title("Top-down footfall pattern")
    ax.legend(loc="upper left", ncol=3, fontsize=9)
    ymin, ymax = feet[:, :, 1].min(), feet[:, :, 1].max()
    ax.set_ylim(ymin - 0.1, ymax + 0.25)
    if synthetic:
        toy_label(ax, _tag(True), loc="lower right")
    return fig


def stick_figure_gif(data, synthetic, seconds=2.4, every=3):
    """Animated side-view stick figure (body line + straight legs to the
    feet) rendered to GIF bytes."""
    fps = config.KINE2GO_FPS
    n = min(len(data), int(seconds * fps))
    feet = data[:n, config.KINE2GO_FOOT_COLS].reshape(n, 4, 3)
    base = data[:n, L["base_pos"]]
    frames = []
    fig, ax = plt.subplots(figsize=(6.4, 2.8), dpi=80)
    for k in range(0, n, every):
        ax.clear()
        bx, bz = base[k, 0], base[k, 2]
        front, rear = (bx + _HIP_X, bz), (bx - _HIP_X, bz)
        ax.plot([rear[0], front[0]], [bz, bz], color=config.NAVY, lw=7, solid_capstyle="round")
        cols = [config.NAVY, config.ACCENT, config.ACCENT_2, "#8E6CEF"]
        for f in range(4):
            hip = front if f < 2 else rear
            ax.plot([hip[0], feet[k, f, 0]], [hip[1], feet[k, f, 2]], color=cols[f], lw=3)
            ax.scatter([feet[k, f, 0]], [feet[k, f, 2]], color=cols[f], s=25, zorder=3)
        ax.axhline(feet[:, :, 2].min(), color=config.GREY, lw=1.5)
        ax.set_xlim(bx - 0.6, bx + 0.6)   # camera follows the dog
        ax.set_ylim(feet[:, :, 2].min() - 0.05, base[:, 2].max() + 0.12)
        ax.set_aspect("equal")
        ax.set_title(f"Simplified stick figure  t = {k / fps:.2f} s"
                     + ("  (SYNTHETIC)" if synthetic else ""), fontsize=11)
        ax.set_yticks([])
        fig.canvas.draw()
        frames.append(Image.fromarray(np.asarray(fig.canvas.buffer_rgba())).convert("RGB").quantize(colors=128, method=Image.Quantize.MEDIANCUT))
    plt.close(fig)
    buf = io.BytesIO()
    frames[0].save(buf, format="GIF", save_all=True, append_images=frames[1:],
                   duration=int(1000 * every / fps), loop=0)
    return buf.getvalue()


def run(download=False, with_gif=True):
    t0 = time.perf_counter()
    motion = load_motion(download=download)
    d, syn = motion["data"], motion["synthetic"]
    out = {
        "figures": {"kine2go_joints": joint_figure(d, syn), "kine2go_feet": foot_figure(d, syn),
                    "kine2go_footfall": footfall_figure(d, syn)},
        "gif": stick_figure_gif(d, syn) if with_gif else None,
        "synthetic": syn,
        "message": motion["message"],
        "shape": tuple(d.shape),
        "duration_s": len(d) / config.KINE2GO_FPS,
        "path": motion["path"],
    }
    out["seconds"] = time.perf_counter() - t0
    return out


if __name__ == "__main__":
    o = run(download=True)
    print(o["message"], o["shape"], f"{o['seconds']:.1f}s", len(o["gif"]) // 1024, "KB gif")
